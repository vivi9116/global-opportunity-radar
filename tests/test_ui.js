'use strict';
const assert=require('node:assert/strict');
const {card,safeURL}=require('../app.js');
const item={id:'unsafe"value',title_zh:'<img src=x onerror=alert(1)>','source_platform':'fixture',source_url:'javascript:alert(1)',financial_evidence:[],action_steps:[],reverse_model:[],platform_ecology:{}};
const output=card(item);
assert.match(output,/^<details class="opportunity"/);
assert.ok(!/<details[^>]*\sopen(?:=|\s|>)/.test(output),'cards start collapsed');
const summary=output.match(/<summary>(.*?)<\/summary>/s)[1];
assert.match(summary,/^<h3>.*<\/h3>$/s,'summary contains the title only');
assert.ok(!output.includes('<img'),'untrusted source text is escaped');
assert.ok(!output.includes('href="javascript:'),'untrusted source links are not executable');
assert.ok(!output.includes('原文金额证据'),'no money section is fabricated');
assert.equal(safeURL('file:///C:/private'),'#');
const legacy=card({...item,title_zh:'CSV task',platform_ecology:{legacy_note:'30分钟竞争、10分钟真实小样：未经统计验证'}});
assert.ok(legacy.includes('10分钟真实小样'));
console.log('UI: collapsed titles, escaping, evidence omission and legacy reminder passed.');
